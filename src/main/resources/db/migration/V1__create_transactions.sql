CREATE TABLE transactions (
    id                UUID                     NOT NULL PRIMARY KEY,
    card_id           VARCHAR(64)              NOT NULL,
    amount            NUMERIC(19, 2)           NOT NULL,
    merchant          VARCHAR(255)             NOT NULL,
    merchant_category VARCHAR(64)              NOT NULL,
    city              VARCHAR(128)             NOT NULL,
    latitude          DOUBLE PRECISION         NOT NULL,
    longitude         DOUBLE PRECISION         NOT NULL,
    transaction_time  TIMESTAMP WITH TIME ZONE NOT NULL,
    risk_score        INT                      NOT NULL,
    decision          VARCHAR(16)              NOT NULL,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_transactions_card_time ON transactions (card_id, transaction_time DESC);

CREATE TABLE transaction_rule_hits (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id UUID         NOT NULL REFERENCES transactions (id),
    rule_name      VARCHAR(64)  NOT NULL,
    points         INT          NOT NULL,
    reason         VARCHAR(255) NOT NULL
);

CREATE INDEX idx_rule_hits_transaction ON transaction_rule_hits (transaction_id);
